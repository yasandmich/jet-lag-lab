// Search airports by code / city / name / country. Falls back to a custom entry
// (needsTz=true) so the user must assign a timezone instead of silently using UTC.
export function searchAirports(q) {
  const n = q.trim().toLowerCase();
  if (!n) return [];
  let out = AIRPORTS.filter(
    (a) =>
      a.code.toLowerCase().includes(n) ||
      a.city.toLowerCase().includes(n) ||
      a.name.toLowerCase().includes(n) ||
      a.country.toLowerCase().includes(n)
  ).slice(0, 22);
  if (out.length === 0 && n.length >= 2) {
    out = [{ code: q.toUpperCase().slice(0, 4), name: 'Custom airport', city: q.trim(), country: 'Custom', tz: null, needsTz: true }];
  }
  return out;
}
